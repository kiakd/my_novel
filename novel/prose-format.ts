// prose-format.ts — post-process จัดรูปคำตอบแชท (กันโมเดลหั่น *วลี* ทีละบรรทัด)
// ใช้หลังได้ข้อความเต็มจากโมเดล / ตอนแสดง stream ฝั่ง client

/**
 * รวมบล็อก *...* ที่ติดกัน (คั่นแค่ช่องว่าง/ขึ้นบรรทัด) ให้เป็นย่อหน้าเดียว
 * ไม่ยุ่งบทพูด "..." · header [⏰..] · [💭..] · [[state:..]]
 *
 * ตัวอย่าง:
 *   *เธอกลืนน้ำลาย*\n\n*ด้วยความยากลำบาก*  →  *เธอกลืนน้ำลาย ด้วยความยากลำบาก*
 */
export function mergeFragmentedProse(text: string): string {
  if (!text || !text.includes('*')) return text;

  // วนซ้ำจนกว่าจะไม่เหลือคู่ *...* ติดกัน (กรณีหั่นเป็น 5–10 ก้อน)
  // จับเฉพาะดอกจันคู่ที่ไม่มี * ข้างใน — ตรงฟอร์แมตแชท (*การกระทำ*)
  const adj = /\*([^*\n][^*]*?)\*\s*(?:\n\s*)+\*([^*\n][^*]*?)\*/g;

  let prev = '';
  let cur = text;
  let guard = 0;
  while (cur !== prev && guard++ < 200) {
    prev = cur;
    cur = cur.replace(adj, (_m, a: string, b: string) => {
      const left = a.replace(/\s+/g, ' ').trim();
      const right = b.replace(/\s+/g, ' ').trim();
      if (!left || !right) return `*${left || right}*`;
      // ถ้าชิ้นขวาสั้นมาก (< 40 ตัว) หรือชิ้นซ้ายก็ไม่ยาวนัก — รวม (สไตล์หั่นวลี)
      // ถ้าทั้งคู่ยาวมากอยู่แล้ว ยังรวมได้เมื่อถูกแยกด้วย newline เปล่า ๆ (ยังถือว่าเป็นย่อหน้าเดียวที่ถูกหั่น)
      return `*${left} ${right}*`;
    });
  }

  // เก็บบรรทัดว่างเกิน: ลด \n{3,} → \n\n (ระหว่างบล็อกชนิดต่างกันยังเว้น 1 บรรทัด)
  cur = cur.replace(/\n{3,}/g, '\n\n');
  return cur;
}
