export interface ChatCharLite {
  name: string;
  appearance?: string;
  outfit?: string;
  description?: string;
  mindset?: string;
  behavior?: string;
  pronounSelf?: string;
  pronounOther?: string;
  speechTone?: string;
  voiceExamples?: string;
  scenario?: string;
  likes?: string;
  dislikes?: string;
  guard?: number;
  power?: string;
  powerStanding?: boolean;   // โหมดบังคับถาวร — อำนาจมีผลทุกเทิร์น ไม่ต้องพิมพ์ (⚡ ...) นำหน้า
}

/** บทบาทของผู้เล่นในแชท (มินิการ์ดฝั่งผู้เล่น) — ฉีดให้ตัวละครรู้จัก+โต้ตอบตามบท */
export interface PlayerPersonaLite {
  name?: string;
  role?: string;
  appearance?: string;
}

/** section "ตัวตนผู้เล่น" — วางใกล้ส่วนตัวตนตัวละคร ให้ตัวละครโต้ตอบกับผู้เล่นตามบทที่สวม */
function playerSection(p?: PlayerPersonaLite): string {
  if (!p || !(p.name?.trim() || p.role?.trim() || p.appearance?.trim())) return '';
  const L: string[] = [];
  if (p.name?.trim()) L.push(`- ชื่อ/ที่เรียก: ${p.name.trim()}`);
  if (p.role?.trim()) L.push(`- บทบาท/สถานะ: ${p.role.trim()}`);
  if (p.appearance?.trim()) L.push(`- รูปลักษณ์: ${p.appearance.trim()}`);
  return `\n=== ตัวตนของ "ผู้เล่น" (คนที่คุณกำลังโต้ตอบด้วยในฉากนี้) ===\n${L.join('\n')}\n⚠️ ผู้เล่นสวมบทเป็นตัวละครนี้ — เรียกชื่อ โต้ตอบ และบรรยายปฏิกิริยาต่อผู้เล่นให้สอดคล้องกับตัวตนนี้เสมอ ห้ามสมมติ/เปลี่ยนตัวตนผู้เล่นใหม่เอง (ยังคงกฎเดิม: ห้ามบรรยายความคิด/ตัดสินใจ "แทน" ผู้เล่น)\n`;
}

/** ป้ายระดับความสัมพันธ์ -100..100 */
export function relLevel(rel: number): string {
  if (rel <= -50) return 'ศัตรู (เกลียด/เป็นปฏิปักษ์)';
  if (rel < 0) return 'ไม่ชอบ/ระแวง';
  if (rel < 20) return 'คนแปลกหน้า';
  if (rel < 50) return 'เริ่มคุ้นเคย';
  if (rel < 75) return 'สนิทสนม';
  if (rel < 90) return 'ชอบ/ใกล้ชิด';
  return 'คนรัก';
}

function bulletize(s?: string): string {
  if (!s?.trim()) return '';
  return s.split('\n').map((l) => l.trim()).filter(Boolean).map((l) => `  - ${l.replace(/^[-•]\s*/, '')}`).join('\n');
}

/** section lorebook — ข้อเท็จจริงเฉพาะฉากที่ client เลือกมาแล้ว (keyword match) วางใกล้ "ท้าย" prompt ให้มีอิทธิพลสูง */
function loreSection(lore?: string[]): string {
  if (!lore?.length) return '';
  return `\n=== ข้อเท็จจริงที่เกี่ยวกับฉากตอนนี้ (ยึดตามนี้เสมอ ห้ามขัด) ===\n${lore.map((l) => `- ${l.trim()}`).join('\n')}\n`;
}

/** section บัตรสถานะ — ข้อเท็จจริง "ปัจจุบัน" แบบ field ตายตัว (กัน identity/สถานะเพี้ยน — แรงกว่า prose ใน summary) */
function stateSection(state?: string): string {
  if (!state?.trim()) return '';
  return `\n=== สถานะปัจจุบัน (ข้อเท็จจริงล่าสุด — ยึดตามนี้เด็ดขาด ห้ามขัด/ห้ามย้อนกลับ) ===\n${state.trim()}\n`;
}

